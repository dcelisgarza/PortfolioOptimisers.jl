# Examples introduction

Each example takes one topic of `PortfolioOptimisers.jl` and works through it on real price data. The first examples load prices and run a mean-variance optimisation. Later ones cover moments and priors, the optimisers, constraints and costs, validation and tuning, post-processing, and complete investor profiles.

For a shorter tour of the package, read the [user guide](https://dcelisgarza.github.io/PortfolioOptimisers.jl/stable/user_guide/00_User_Guide).
